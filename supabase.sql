create table if not exists public.neru_choices (
  id bigint generated by default as identity primary key,
  event_id text not null,
  name text not null,
  share jsonb not null default '[]'::jsonb,
  first_choice text,
  main_choice text,
  dessert_choice text,
  updated_at timestamptz not null default now(),
  unique (event_id, name)
);

alter table public.neru_choices enable row level security;

drop policy if exists "neru read" on public.neru_choices;
create policy "neru read" on public.neru_choices
for select to anon using (event_id = 'neru-2026-11-07');

drop policy if exists "neru insert" on public.neru_choices;
create policy "neru insert" on public.neru_choices
for insert to anon with check (event_id = 'neru-2026-11-07');

drop policy if exists "neru update" on public.neru_choices;
create policy "neru update" on public.neru_choices
for update to anon using (event_id = 'neru-2026-11-07')
with check (event_id = 'neru-2026-11-07');

-- Para que las actualizaciones aparezcan en tiempo real.
alter publication supabase_realtime add table public.neru_choices;
